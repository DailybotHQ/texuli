/**
 * The web half of the dual-target golden gate (spec/Compose design 7.2): each
 * spec golden blueprint goes through the web validator and sink-free renderer
 * (`@texuli/catalog/validate`, untrusted tier), and its render tree becomes a
 * canonical semantic trace under `../semantics.json`. The native half
 * (`conformance/src/jvmTest`) must produce the same traces.
 *
 * It also generates the Kotlin rule table (`SemanticRules.kt`) from the same
 * `semantics.json`, so both targets apply one set of rules.
 *
 *   pnpm exec tsx native/conformance/web/trace.ts           (check; exit 1 on drift)
 *   pnpm exec tsx native/conformance/web/trace.ts --write   (refresh traces and rules)
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { buildCatalog } from '@texuli/catalog/build';
import { discoverManifestGroups } from '@texuli/catalog/build/node';
import { formulaConditions } from '@texuli/catalog/render/conditions';
import { renderCatalogFromBuild } from '@texuli/catalog/render/renderer';
import { validateDraft } from '@texuli/catalog/validate';
import { formatJson } from '../../../packages/spec/src/format.ts';
import { type Rule, semantics, traceNode } from './trace-rules.ts';

const HERE = import.meta.dirname;
const REPO = join(HERE, '../../..');
const GOLDEN = join(REPO, 'packages/spec/fixtures/golden');
const EXPECTED = join(HERE, '../expected');
const RULES_KT = join(
  HERE,
  '../../texuli-spec/src/commonMain/kotlin/com/texuli/spec/runtime/SemanticRules.kt'
);
const kt = (value: string) => JSON.stringify(value).replace(/\$/g, '\\$');
function ruleKt(rule: Rule): string {
  const parts = [`role = ${kt(rule.role)}`];
  if (rule.name?.length) parts.push(`name = listOf(${rule.name.map(kt).join(', ')})`);
  if (rule.level) parts.push(`level = ${kt(rule.level)}`);
  return `SemanticRule(${parts.join(', ')})`;
}

/** The Kotlin twin of semantics.json, deterministic. */
export function semanticRulesKotlin(): string {
  const lines = [
    '// Generated by native/conformance/web/trace.ts from native/conformance/semantics.json. Do not edit.',
    'package com.texuli.spec.runtime',
    '',
    '/** One semantic rule: the role, the props tried for the name, the prop holding a heading level. */',
    'data class SemanticRule(val role: String, val name: List<String> = emptyList(), val level: String? = null)',
    '',
    '/** The shared semantic rules (see semantics.json). */',
    'object SemanticRules {',
    `    val default: SemanticRule = ${ruleKt(semantics.default)}`,
    '',
    '    /** The first rule that matches wins: an exact id or a prefix, in file order. */',
    '    val components: List<Pair<String, SemanticRule>> = listOf(',
    ...semantics.components.map(
      (r) =>
        `        ${kt(r.id !== undefined ? `id:${r.id}` : `prefix:${r.prefix}`)} to ${ruleKt(r)},`
    ),
    '    )',
    '',
    '    /** Block rules by `block.type`, for `blocks-*` ids. */',
    '    val blocks: Map<String, SemanticRule> = mapOf(',
    ...Object.entries(semantics.blocks).map(([type, r]) => `        ${kt(type)} to ${ruleKt(r)},`),
    '    )',
    '}',
    '',
  ];
  return lines.join('\n');
}

const build = await buildCatalog(await discoverManifestGroups());
const catalog = renderCatalogFromBuild(build.catalog);
const write = process.argv.includes('--write');
const drift: string[] = [];
const goldens = readdirSync(GOLDEN)
  .filter((f) => f.endsWith('.json'))
  .sort();
for (const file of goldens) {
  const name = basename(file, '.json');
  const envelope = JSON.parse(readFileSync(join(GOLDEN, file), 'utf8'));
  const validation = validateDraft(envelope, {
    catalog,
    tier: 'untrusted',
    // The conditional golden is evaluated with explicit fictional host data.
    // The native semantic trace includes its node when the condition is true.
    conditions: formulaConditions,
    conditionInputs: { closed: 38, blocked: 2 },
  });
  if (!validation.ok) {
    console.error(`${name}: the golden does not validate on the web target`);
    process.exit(1);
  }
  const text = formatJson({ golden: name, trace: validation.roots.map(traceNode) });
  const target = join(EXPECTED, `${name}.trace.json`);
  if (write) writeFileSync(target, text);
  else if (!existsSync(target) || readFileSync(target, 'utf8') !== text) drift.push(name);
}
const rules = semanticRulesKotlin();
if (write) writeFileSync(RULES_KT, rules);
else if (!existsSync(RULES_KT) || readFileSync(RULES_KT, 'utf8') !== rules)
  drift.push('SemanticRules.kt');
if (drift.length > 0) {
  console.error(`web trace drift: ${drift.join(', ')} (run with --write and review)`);
  process.exit(1);
}
console.log(`${write ? 'wrote' : 'checked'} ${goldens.length} web traces`);
