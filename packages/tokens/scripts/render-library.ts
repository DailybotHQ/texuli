/**
 * Pure renderers for the generated theme library surfaces (G125, G126):
 * `src/library-expand/metadata.ts` (the compact expand catalog rows) and
 * `src/library-ids/ids.ts` (every library theme id, by set). Both are read
 * from the libraries' own sources: the port records (`PORT_THEME_RECORDS`)
 * and the expand definition modules, in `EXPAND_THEME_DEFINITION_LOADERS`
 * order. `generate.ts` writes them; the tests compare them with the files, so
 * a hand edit or a stale file fails.
 */
import { EXPAND_THEME_DEFINITION_LOADERS } from '../src/library-expand/loaders.ts';
import { PORT_THEME_RECORDS } from '../src/library-port/records.ts';
import type { LibraryThemeDefinition } from '../src/library-port/types.ts';

const GENERATED =
  'generated by `pnpm exec tsx packages/tokens/scripts/generate.ts`; do not edit by hand';

/**
 * The expand definitions in catalog order: the built-ins in the loader
 * table's order, then every curated theme sorted by id.
 */
export async function expandDefinitions(): Promise<LibraryThemeDefinition[]> {
  const all = await loadExpandDefinitions();
  const builtin = all.filter((definition) => definition.category === 'builtin');
  const curated = all
    .filter((definition) => definition.category !== 'builtin')
    .sort((left, right) => (left.id < right.id ? -1 : left.id > right.id ? 1 : 0));
  return [...builtin, ...curated];
}

async function loadExpandDefinitions(): Promise<LibraryThemeDefinition[]> {
  const loaders = EXPAND_THEME_DEFINITION_LOADERS as Record<
    string,
    () => Promise<{ default: LibraryThemeDefinition }>
  >;
  const definitions: LibraryThemeDefinition[] = [];
  for (const [id, load] of Object.entries(loaders)) {
    const { default: definition } = await load();
    if (definition.id !== id) {
      throw new Error(`library-expand: loader "${id}" returns definition "${definition.id}"`);
    }
    definitions.push(definition);
  }
  return definitions;
}

/** A TypeScript string literal in the repository's Biome style (single quotes unless it holds one). */
function quote(text: string): string {
  const escaped = text.replaceAll('\\', '\\\\');
  if (text.includes("'") && !text.includes('"')) return `"${escaped}"`;
  return `'${escaped.replaceAll("'", "\\'")}'`;
}

function rowFields(definition: LibraryThemeDefinition): string[] {
  return [
    quote(definition.id),
    quote(definition.name),
    quote(definition.category),
    quote(definition.collection ?? 'industry'),
    quote(definition.contrastLevel ?? 'AA'),
    definition.darkFirst ? '1' : '0',
    quote(definition.seed),
    quote(definition.neutral ?? ''),
    quote(definition.tags.join(',')),
    quote((definition.mood ?? []).join(',')),
    // G126: the full description, never a cut. The metadata is the catalog a
    // browser shows, so it reads as complete sentences.
    quote(definition.description),
  ];
}

/** `src/library-expand/metadata.ts`. */
export async function renderExpandMetadata(): Promise<string> {
  const definitions = await expandDefinitions();
  const rows = definitions
    .map(
      (definition) =>
        `  [\n${rowFields(definition)
          .map((f) => `    ${f},`)
          .join('\n')}\n  ],`
    )
    .join('\n');
  return `// ${GENERATED}.
import type { LibraryThemeMeta } from '../library-port/types.ts';

/**
 * Compact expand catalog rows (listing and search only): the built-ins
 * first, then the curated themes sorted by id.
 * Tuple: [id, name, category, collection, contrast, darkFirst, seed, neutral, tagsCsv, moodCsv, description]
 * The description is the definition's full sentence (G126). Secondary,
 * font, radius, density and style live on the lazy theme modules.
 */
export const EXPAND_THEME_ROWS = [
${rows}
] as const;

export function expandRowToMeta(row: (typeof EXPAND_THEME_ROWS)[number]): LibraryThemeMeta {
  const [
    id,
    name,
    category,
    collection,
    contrastLevel,
    darkFirst,
    seed,
    neutral,
    tagsCsv,
    moodCsv,
    description,
  ] = row;
  return {
    id,
    name,
    description: description || name,
    category,
    tags: tagsCsv ? tagsCsv.split(',') : [],
    collection: collection as LibraryThemeMeta['collection'],
    mood: (moodCsv ? moodCsv.split(',') : []) as LibraryThemeMeta['mood'],
    darkFirst: darkFirst === 1,
    contrastLevel: contrastLevel as LibraryThemeMeta['contrastLevel'],
    seed,
    neutral: neutral as LibraryThemeMeta['neutral'],
  };
}
`;
}

function idList(name: string, doc: string, ids: readonly string[]): string {
  return `/** ${doc} */
export const ${name} = [
${ids.map((id) => `  ${quote(id)},`).join('\n')}
] as const;
`;
}

/** The three disjoint id sets: built-ins, the port and the rest of the expanded set. */
export async function libraryIdSets(): Promise<{
  builtin: string[];
  port: string[];
  expand: string[];
}> {
  const expand = await expandDefinitions();
  return {
    builtin: expand.filter((d) => d.category === 'builtin').map((d) => d.id),
    port: PORT_THEME_RECORDS.map((record) => record.id),
    expand: expand.filter((d) => d.category !== 'builtin').map((d) => d.id),
  };
}

/** `src/library-ids/ids.ts`. */
export async function renderLibraryIds(): Promise<string> {
  const sets = await libraryIdSets();
  return `// ${GENERATED}.
// Read from the port records and the expand definition modules, so the ids never drift.

${idList(
  'BUILTIN_THEME_IDS',
  `The ${sets.builtin.length} Protoyard built-in ids, first in \`@texuli/tokens/library-expand\`.`,
  sets.builtin
)}
${idList(
  'PORT_THEME_IDS',
  `The ${sets.port.length} ported library ids (\`@texuli/tokens/library\`).`,
  sets.port
)}
${idList(
  'EXPAND_THEME_IDS',
  `The ${sets.expand.length} curated ids of \`@texuli/tokens/library-expand\` after the built-ins.`,
  sets.expand
)}`;
}
