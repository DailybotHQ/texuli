export function getPortThemeRecord(id: string): LibraryThemeDefinition | undefined {
  return byIdMap.get(id);
}

export function requirePortThemeRecord(id: string): LibraryThemeDefinition {
  const record = byIdMap.get(id);
  if (!record) {
    throw new TypeError(
      `Unknown library theme "${id}". Known ids: ${PORT_THEME_RECORDS.map((r) => r.id).join(', ')}`
    );
  }
  return record;
}

