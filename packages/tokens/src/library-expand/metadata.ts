export function expandRowToMeta(row: (typeof EXPAND_THEME_ROWS)[number]): LibraryThemeMeta {
  const [
    id,
    name,
    category,
    collection,
    contrastLevel,
    darkFirst,
    seed,
    neutral,
    tagsCsv,
    moodCsv,
    description,
  ] = row;
  return {
    id,
    name,
    description: description || name,
    category,
    tags: tagsCsv ? tagsCsv.split(',') : [],
    collection: collection as LibraryThemeMeta['collection'],
    mood: (moodCsv ? moodCsv.split(',') : []) as LibraryThemeMeta['mood'],
    darkFirst: darkFirst === 1,
    contrastLevel: contrastLevel as LibraryThemeMeta['contrastLevel'],
    seed,
    neutral: neutral as LibraryThemeMeta['neutral'],
  };
}
