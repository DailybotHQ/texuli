import type { SpecCatalog, SpecDeprecation, SpecPropSchema } from '../catalog.ts';
import type { Schema } from '../dialect.ts';
import {
  assertSupported,
  defName,
  isRecordType,
  isStringEnum,
  pascal,
  refType,
  rootName,
  type SchemaUnit,
  type Stamp,
  upperSnake,
  wrap,
} from './shared.ts';

/**
 * Deterministic Kotlin projections of the spec, written as committed text
 * (no Kotlin toolchain here): data classes, closed enums and static
 * decoders over a small `JsonValue` model, with no library dependency.
 * Decoders check JSON types, required and unknown fields, enums and
 * constants; patterns and limits stay with the shared validator.
 */

export const KOTLIN_PACKAGE = 'com.texuli.spec';
const INDENT = '    ';

function header(source: string, stamp: Stamp): string[] {
  return [
    `// Generated by @texuli/spec from ${source}. Do not edit: run the spec generator.`,
    `// Spec ${stamp.specVersion}, digest ${stamp.specDigest}`,
    '',
    `package ${KOTLIN_PACKAGE}`,
    '',
  ];
}

/** A Kotlin string literal (escapes backslash, quote, dollar and controls). */
export function kotlinString(value: string): string {
  let out = '';
  for (const char of value) {
    const code = char.codePointAt(0) ?? 0;
    if (char === '\\') out += '\\\\';
    else if (char === '"') out += '\\"';
    else if (char === '$') out += '\\$';
    else if (char === '\n') out += '\\n';
    else if (code < 0x20) out += `\\u${code.toString(16).padStart(4, '0')}`;
    else out += char;
  }
  return `"${out}"`;
}

function kdoc(text: string | undefined, indent: string): string[] {
  if (!text) return [];
  // A line starting with `@` would read as a KDoc tag: quote package names.
  const quoted = text.replace(/(^|\s)(@[\w/.-]+)/g, '$1`$2`');
  return [
    `${indent}/**`,
    ...wrap(quoted, 96 - indent.length).map((line) => `${indent} * ${line}`),
    `${indent} */`,
  ];
}

const KEYWORDS = new Set([
  'as',
  'class',
  'fun',
  'in',
  'is',
  'object',
  'package',
  'typealias',
  'val',
  'var',
  'when',
]);
function field(name: string): string {
  return KEYWORDS.has(name) ? `\`${name}\`` : name;
}

/**
 * The Kotlin property for a wire name: a leading `$` is stripped (`$state` →
 * `state`), because `$` starts a string template in Kotlin. The wire name
 * itself is always emitted through {@link kotlinString}.
 */
export function kotlinProperty(name: string): string {
  return name.startsWith('$') ? name.slice(1) : name;
}

/** `$` escaped for a Kotlin string template (`\$state`). */
function templateText(name: string): string {
  return name.replaceAll('$', '\\$');
}

interface KotlinContext {
  unit: SchemaUnit;
  /** Extra enum classes found inline in properties, keyed by type name. */
  inlineEnums: Map<string, Schema & { enum: readonly string[] }>;
}

function kotlinType(node: Schema, ctx: KotlinContext, inlineName: string): string {
  if (node.$ref !== undefined) return refType(ctx.unit, node.$ref);
  if (node.const !== undefined) return typeof node.const === 'string' ? 'String' : 'Long';
  if (isStringEnum(node)) {
    ctx.inlineEnums.set(inlineName, node);
    return inlineName;
  }
  switch (node.type) {
    case undefined:
      return 'JsonValue';
    case 'string':
      return 'String';
    case 'integer':
      return 'Long';
    case 'number':
      return 'Double';
    case 'boolean':
      return 'Boolean';
    case 'array':
      return `List<${node.items ? kotlinType(node.items, ctx, inlineName) : 'JsonValue'}>`;
    case 'object':
      if (node.properties !== undefined) {
        throw new Error(`${ctx.unit.source}: inline object types are not supported; use $defs`);
      }
      return `Map<String, ${node.additionalProperties ? kotlinType(node.additionalProperties, ctx, inlineName) : 'JsonValue'}>`;
  }
}

/** A decode expression for `value` (a `JsonValue`) at path expression `path`. */
function decodeExpr(
  node: Schema,
  value: string,
  path: string,
  ctx: KotlinContext,
  inlineName: string
): string {
  if (node.$ref !== undefined) {
    const name = refType(ctx.unit, node.$ref);
    const target = ctx.unit.schema.$defs?.[node.$ref.slice('#/$defs/'.length)];
    // Records and enums decode through their companion; aliases through a function.
    return target && (isRecordType(target) || isStringEnum(target))
      ? `${name}.decode(${value}, ${path})`
      : `decode${name}(${value}, ${path})`;
  }
  if (node.const !== undefined) {
    return typeof node.const === 'string'
      ? `${value}.constant(${kotlinString(node.const)}, ${path})`
      : `${value}.constant(${node.const}L, ${path})`;
  }
  if (isStringEnum(node)) return `${inlineName}.decode(${value}, ${path})`;
  switch (node.type) {
    case undefined:
      return value;
    case 'string':
      return `${value}.str(${path})`;
    case 'integer':
      return `${value}.long(${path})`;
    case 'number':
      return `${value}.double(${path})`;
    case 'boolean':
      return `${value}.bool(${path})`;
    case 'array': {
      const item = node.items
        ? decodeExpr(node.items, 'item', '"$p[$i]"', ctx, inlineName)
        : 'item';
      return `(${path}).let { p -> ${value}.arrValues(p).mapIndexed { i, item -> ${item} } }`;
    }
    case 'object': {
      const inner = node.additionalProperties
        ? decodeExpr(node.additionalProperties, 'item', '"$p.$k"', ctx, inlineName)
        : 'item';
      return `(${path}).let { p -> ${value}.obj(p).mapValues { (k, item) -> ${inner} } }`;
    }
  }
}

function enumClass(name: string, values: readonly string[], description?: string): string[] {
  const names = values.map(upperSnake);
  if (new Set(names).size !== names.length) throw new Error(`${name}: enum entries collide`);
  return [
    ...kdoc(description, ''),
    `enum class ${name}(val wire: String) {`,
    ...values.map((value, i) => `${INDENT}${names[i]}(${kotlinString(value)}),`),
    `${INDENT};`,
    '',
    `${INDENT}companion object {`,
    `${INDENT}${INDENT}fun decode(json: JsonValue, path: String): ${name} {`,
    `${INDENT}${INDENT}${INDENT}val wire = json.str(path)`,
    `${INDENT}${INDENT}${INDENT}return entries.firstOrNull { it.wire == wire }`,
    `${INDENT}${INDENT}${INDENT}${INDENT}?: throw SpecDecodeException(path, "unknown value \\"$wire\\"")`,
    `${INDENT}${INDENT}}`,
    `${INDENT}}`,
    '}',
  ];
}

function dataClass(name: string, node: Schema, ctx: KotlinContext): string[] {
  const required = new Set(node.required ?? []);
  const props = Object.entries(node.properties ?? {});
  const params: string[] = [];
  const args: string[] = [];
  const seen = new Set<string>();
  for (const [prop, child] of props) {
    const property = kotlinProperty(prop);
    if (seen.has(property)) throw new Error(`${name}: Kotlin property "${property}" collides`);
    seen.add(property);
    const inlineName = `${name}${pascal(property)}`;
    const type = kotlinType(child, ctx, inlineName);
    const path = `"$path.${templateText(prop)}"`;
    if (required.has(prop)) {
      const defaultValue =
        typeof child.const === 'string'
          ? ` = ${kotlinString(child.const)}`
          : child.const !== undefined
            ? ` = ${child.const}L`
            : '';
      params.push(`${INDENT}val ${field(property)}: ${type}${defaultValue},`);
      args.push(
        `${INDENT}${INDENT}${INDENT}${INDENT}${field(property)} = ${decodeExpr(child, `fields.required(${kotlinString(prop)}, path)`, path, ctx, inlineName)},`
      );
    } else {
      params.push(`${INDENT}val ${field(property)}: ${type}? = null,`);
      args.push(
        `${INDENT}${INDENT}${INDENT}${INDENT}${field(property)} = fields[${kotlinString(prop)}]?.let { ${decodeExpr(child, 'it', path, ctx, inlineName)} },`
      );
    }
  }
  const allowed = props.map(([prop]) => kotlinString(prop)).join(', ');
  return [
    ...kdoc(node.description, ''),
    `data class ${name}(`,
    ...params,
    ') {',
    `${INDENT}companion object {`,
    `${INDENT}${INDENT}private val FIELDS = setOf(${allowed})`,
    '',
    `${INDENT}${INDENT}fun decode(json: JsonValue, path: String = "\\$"): ${name} {`,
    `${INDENT}${INDENT}${INDENT}val fields = json.obj(path)`,
    `${INDENT}${INDENT}${INDENT}fields.requireOnly(FIELDS, path)`,
    `${INDENT}${INDENT}${INDENT}return ${name}(`,
    ...args,
    `${INDENT}${INDENT}${INDENT})`,
    `${INDENT}${INDENT}}`,
    `${INDENT}}`,
    '}',
  ];
}

function aliasBlock(name: string, node: Schema, ctx: KotlinContext): string[] {
  const type = kotlinType(node, ctx, `${name}Value`);
  return [
    ...kdoc(node.description, ''),
    `typealias ${name} = ${type}`,
    '',
    `fun decode${name}(json: JsonValue, path: String): ${name} =`,
    `${INDENT}${decodeExpr(node, 'json', 'path', ctx, `${name}Value`)}`,
  ];
}

/** One schema document as a Kotlin file of data classes, enums and decoders. */
export function schemaToKotlin(unit: SchemaUnit, stamp: Stamp): string {
  assertSupported(unit);
  const ctx: KotlinContext = { unit, inlineEnums: new Map() };
  const blocks: string[][] = [];
  const entries: [string, Schema][] = [
    ...Object.entries(unit.schema.$defs ?? {}).map(([def, node]): [string, Schema] => [
      defName(unit, def),
      node,
    ]),
    [rootName(unit), unit.schema],
  ];
  for (const [name, node] of entries) {
    if (isRecordType(node)) blocks.push(dataClass(name, node, ctx));
    else if (isStringEnum(node)) blocks.push(enumClass(name, node.enum, node.description));
    else blocks.push(aliasBlock(name, node, ctx));
  }
  for (const [name, node] of [...ctx.inlineEnums.entries()].sort(([a], [b]) => (a < b ? -1 : 1))) {
    blocks.push(enumClass(name, node.enum, node.description));
  }
  return `${[...header(unit.source, stamp), blocks.map((b) => b.join('\n')).join('\n\n')].join('\n')}\n`;
}

/** The JSON model and decode helpers every generated decoder uses. */
export function kotlinJsonRuntime(stamp: Stamp): string {
  const lines = [
    ...header('the spec generator (JSON runtime)', stamp),
    '/** A parsed JSON value. Hosts convert their parser output into it. */',
    'sealed interface JsonValue {',
    `${INDENT}data class Str(val value: String) : JsonValue`,
    `${INDENT}data class Num(val value: Double) : JsonValue`,
    `${INDENT}data class Bool(val value: Boolean) : JsonValue`,
    `${INDENT}data class Arr(val items: List<JsonValue>) : JsonValue`,
    `${INDENT}data class Obj(val fields: Map<String, JsonValue>) : JsonValue`,
    `${INDENT}data object Null : JsonValue`,
    '}',
    '',
    '/** A value that does not match the spec, with its JSON path. */',
    'class SpecDecodeException(val path: String, message: String) :',
    `${INDENT}IllegalArgumentException("$path: $message")`,
    '',
    'internal fun JsonValue.obj(path: String): Map<String, JsonValue> =',
    `${INDENT}(this as? JsonValue.Obj)?.fields ?: throw SpecDecodeException(path, "expected an object")`,
    '',
    'internal fun JsonValue.arrValues(path: String): List<JsonValue> =',
    `${INDENT}(this as? JsonValue.Arr)?.items ?: throw SpecDecodeException(path, "expected an array")`,
    '',
    'internal fun JsonValue.str(path: String): String =',
    `${INDENT}(this as? JsonValue.Str)?.value ?: throw SpecDecodeException(path, "expected a string")`,
    '',
    'internal fun JsonValue.double(path: String): Double {',
    `${INDENT}val number = (this as? JsonValue.Num)?.value`,
    `${INDENT}if (number == null || !number.isFinite()) throw SpecDecodeException(path, "expected a number")`,
    `${INDENT}return number`,
    '}',
    '',
    'internal fun JsonValue.long(path: String): Long {',
    `${INDENT}val number = double(path)`,
    `${INDENT}if (number % 1.0 != 0.0) throw SpecDecodeException(path, "expected an integer")`,
    `${INDENT}return number.toLong()`,
    '}',
    '',
    'internal fun JsonValue.bool(path: String): Boolean =',
    `${INDENT}(this as? JsonValue.Bool)?.value ?: throw SpecDecodeException(path, "expected a boolean")`,
    '',
    'internal fun JsonValue.constant(expected: String, path: String): String {',
    `${INDENT}val value = str(path)`,
    `${INDENT}if (value != expected) throw SpecDecodeException(path, "expected \\"$expected\\"")`,
    `${INDENT}return value`,
    '}',
    '',
    'internal fun JsonValue.constant(expected: Long, path: String): Long {',
    `${INDENT}val value = long(path)`,
    `${INDENT}if (value != expected) throw SpecDecodeException(path, "expected $expected")`,
    `${INDENT}return value`,
    '}',
    '',
    'internal fun Map<String, JsonValue>.required(name: String, path: String): JsonValue =',
    `${INDENT}this[name] ?: throw SpecDecodeException("$path.$name", "is required")`,
    '',
    '/** Unknown fields fail closed. */',
    'internal fun Map<String, JsonValue>.requireOnly(allowed: Set<String>, path: String) {',
    `${INDENT}val unknown = keys.firstOrNull { it !in allowed }`,
    `${INDENT}if (unknown != null) throw SpecDecodeException("$path.$unknown", "is not allowed")`,
    '}',
    '',
  ];
  return lines.join('\n');
}

function deprecationExpr(value: SpecDeprecation): string {
  const replacement =
    value.replacement === undefined ? '' : `, replacement = ${kotlinString(value.replacement)}`;
  return `SpecDeprecation(since = ${kotlinString(value.since)}${replacement})`;
}

/** A `SpecPropSchema(...)` constructor call, recursively; only the keywords present. */
function propSchemaExpr(schema: SpecPropSchema): string {
  const args: string[] = [];
  const number = (value: number) => (Number.isInteger(value) ? `${value}.0` : String(value));
  if (schema.type !== undefined) args.push(`type = SpecPropSchemaType.${upperSnake(schema.type)}`);
  if (schema.description !== undefined)
    args.push(`description = ${kotlinString(schema.description)}`);
  if (schema.properties !== undefined) {
    const entries = Object.entries(schema.properties).map(
      ([name, child]) => `${kotlinString(name)} to ${propSchemaExpr(child)}`
    );
    args.push(`properties = mapOf(${entries.join(', ')})`);
  }
  if (schema.required !== undefined)
    args.push(`required = listOf(${schema.required.map(kotlinString).join(', ')})`);
  if (schema.additionalProperties !== undefined) {
    args.push(`additionalProperties = ${propSchemaExpr(schema.additionalProperties)}`);
  }
  if (schema.items !== undefined) args.push(`items = ${propSchemaExpr(schema.items)}`);
  if (schema.enum !== undefined)
    args.push(`enum = listOf(${schema.enum.map(kotlinString).join(', ')})`);
  for (const key of ['minLength', 'maxLength', 'minItems', 'maxItems'] as const) {
    const value = schema[key];
    if (value !== undefined) args.push(`${key} = ${value}L`);
  }
  for (const key of ['minimum', 'maximum'] as const) {
    const value = schema[key];
    if (value !== undefined) args.push(`${key} = ${number(value)}`);
  }
  if (schema.$ref !== undefined) args.push(`ref = ${kotlinString(schema.$ref)}`);
  return `SpecPropSchema(${args.join(', ')})`;
}

/** The catalog vocabulary as a Kotlin registry of `SpecComponent` values. */
export function vocabularyToKotlin(catalog: SpecCatalog, stamp: Stamp): string {
  const ids = catalog.components.map((c) => c.id);
  const optional = (value: string | undefined) => (value === undefined ? 'null' : value);
  const lines = [
    ...header('catalog/components.json', stamp),
    ...enumClass('SpecComponentId', ids, 'Every closed component id, sorted.'),
    '',
    '/** The catalog vocabulary: one entry per component id. */',
    'object SpecVocabulary {',
    `${INDENT}const val CATALOG_HASH: String = ${kotlinString(catalog.catalogHash)}`,
    '',
    `${INDENT}val components: List<SpecComponent> = listOf(`,
  ];
  for (const c of catalog.components) {
    lines.push(
      `${INDENT}${INDENT}SpecComponent(`,
      `${INDENT}${INDENT}${INDENT}id = ${kotlinString(c.id)},`,
      `${INDENT}${INDENT}${INDENT}label = ${kotlinString(c.label)},`,
      `${INDENT}${INDENT}${INDENT}summary = ${kotlinString(c.summary)},`,
      `${INDENT}${INDENT}${INDENT}group = ${kotlinString(c.group)},`,
      `${INDENT}${INDENT}${INDENT}placement = SpecComponentPlacement.${upperSnake(c.placement)},`,
      `${INDENT}${INDENT}${INDENT}emit = listOf(${c.emit.map((e) => `SpecComponentEmit.${upperSnake(e)}`).join(', ')}),`,
      `${INDENT}${INDENT}${INDENT}capability = SpecComponentCapability.${upperSnake(c.capability)},`,
      `${INDENT}${INDENT}${INDENT}props = listOf(`
    );
    for (const p of c.props) {
      const enumValues = p.enumValues
        ? `listOf(${p.enumValues.map(kotlinString).join(', ')})`
        : undefined;
      lines.push(
        `${INDENT}${INDENT}${INDENT}${INDENT}SpecProp(`,
        `${INDENT}${INDENT}${INDENT}${INDENT}${INDENT}name = ${kotlinString(p.name)},`,
        `${INDENT}${INDENT}${INDENT}${INDENT}${INDENT}kind = SpecPropKind.${upperSnake(p.kind)},`,
        `${INDENT}${INDENT}${INDENT}${INDENT}${INDENT}required = ${optional(p.required === undefined ? undefined : String(p.required))},`,
        `${INDENT}${INDENT}${INDENT}${INDENT}${INDENT}enumValues = ${optional(enumValues)},`,
        `${INDENT}${INDENT}${INDENT}${INDENT}${INDENT}extension = ${optional(p.extension ? `SpecPropExtension.${upperSnake(p.extension)}` : undefined)},`
      );
      // Emitted only when present, so a catalog without them stays byte-stable.
      if (p.schema)
        lines.push(
          `${INDENT}${INDENT}${INDENT}${INDENT}${INDENT}schema = ${propSchemaExpr(p.schema)},`
        );
      if (p.deprecated) {
        lines.push(
          `${INDENT}${INDENT}${INDENT}${INDENT}${INDENT}deprecated = ${deprecationExpr(p.deprecated)},`
        );
      }
      lines.push(`${INDENT}${INDENT}${INDENT}${INDENT}),`);
    }
    lines.push(`${INDENT}${INDENT}${INDENT}),`);
    if (c.events) {
      lines.push(
        `${INDENT}${INDENT}${INDENT}events = listOf(${c.events.map((e) => `SpecEventName.${upperSnake(e)}`).join(', ')}),`
      );
    }
    if (c.bindable) {
      lines.push(
        `${INDENT}${INDENT}${INDENT}bindable = listOf(${c.bindable.map(kotlinString).join(', ')}),`
      );
    }
    if (c.sourceable) {
      lines.push(
        `${INDENT}${INDENT}${INDENT}sourceable = listOf(${c.sourceable.map(kotlinString).join(', ')}),`
      );
    }
    if (c.deprecated)
      lines.push(`${INDENT}${INDENT}${INDENT}deprecated = ${deprecationExpr(c.deprecated)},`);
    lines.push(`${INDENT}${INDENT}),`);
  }
  lines.push(
    `${INDENT})`,
    '',
    `${INDENT}fun component(id: String): SpecComponent? = components.firstOrNull { it.id == id }`,
    '}',
    ''
  );
  return lines.join('\n');
}
