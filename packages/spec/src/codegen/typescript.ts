import type { SpecCatalog } from '../catalog.ts';
import type { Schema } from '../dialect.ts';
import { LINE_WIDTH } from '../format.ts';
import {
  assertSupported,
  defName,
  isRecordType,
  refType,
  rootName,
  type SchemaUnit,
  type Stamp,
  wrap,
} from './shared.ts';

/**
 * Deterministic TypeScript projections of the spec: strict, erasable types
 * (interfaces, unions, `as const` arrays). The output is already in the
 * repository formatter's style, so it is byte-stable under `pnpm lint`.
 */

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function header(source: string, stamp: Stamp): string {
  return [
    `// Generated by @texuli/spec from ${source}. Do not edit: run the spec generator.`,
    `// Spec ${stamp.specVersion}, digest ${stamp.specDigest}`,
    '',
  ].join('\n');
}

function literal(value: string | number | boolean): string {
  return typeof value === 'string'
    ? `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
    : String(value);
}

function key(name: string): string {
  return IDENTIFIER.test(name) ? name : literal(name);
}

function doc(text: string | undefined, indent: string): string[] {
  if (!text) return [];
  const one = `${indent}/** ${text} */`;
  if (one.length <= LINE_WIDTH) return [one];
  return [
    `${indent}/**`,
    ...wrap(text, LINE_WIDTH - indent.length - 3).map((line) => `${indent} * ${line}`),
    `${indent} */`,
  ];
}

/** The union members of a type, when it is a union of literals. */
function unionMembers(node: Schema): string[] | null {
  if (node.enum !== undefined) return node.enum.map(literal);
  return null;
}

function typeOf(node: Schema, unit: SchemaUnit): string {
  if (node.$ref !== undefined) return refType(unit, node.$ref);
  if (node.const !== undefined) return literal(node.const);
  const members = unionMembers(node);
  if (members) return members.join(' | ');
  switch (node.type) {
    case undefined:
      return 'unknown';
    case 'string':
      return 'string';
    case 'number':
    case 'integer':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'array': {
      const item = node.items ? typeOf(node.items, unit) : 'unknown';
      return item.includes(' | ') ? `readonly (${item})[]` : `readonly ${item}[]`;
    }
    case 'object':
      if (node.properties !== undefined) {
        throw new Error(`${unit.source}: inline object types are not supported; use $defs`);
      }
      return `Readonly<Record<string, ${node.additionalProperties ? typeOf(node.additionalProperties, unit) : 'never'}>>`;
  }
}

/** `head` followed by a type, breaking a long union one member per line. */
function typed(head: string, node: Schema, unit: SchemaUnit, indent: string): string[] {
  const type = typeOf(node, unit);
  const one = `${head} ${type};`;
  const members = unionMembers(node);
  if (one.length <= LINE_WIDTH || !members) return [one];
  const last = members.length - 1;
  return [head, ...members.map((m, i) => `${indent}  | ${m}${i === last ? ';' : ''}`)];
}

function declaration(name: string, node: Schema, unit: SchemaUnit): string[] {
  const lines = doc(node.description, '');
  if (isRecordType(node)) {
    lines.push(`export interface ${name} {`);
    const required = new Set(node.required ?? []);
    for (const [prop, child] of Object.entries(node.properties ?? {})) {
      lines.push(...doc(child.description, '  '));
      const head = `  ${key(prop)}${required.has(prop) ? '' : '?'}:`;
      lines.push(...typed(head, child, unit, '  '));
    }
    lines.push('}');
    return lines;
  }
  lines.push(...typed(`export type ${name} =`, node, unit, ''));
  return lines;
}

/** One schema document as a TypeScript module of types. */
export function schemaToTypeScript(unit: SchemaUnit, stamp: Stamp): string {
  assertSupported(unit);
  const blocks: string[][] = [];
  for (const [def, node] of Object.entries(unit.schema.$defs ?? {})) {
    blocks.push(declaration(defName(unit, def), node, unit));
  }
  blocks.push(declaration(rootName(unit), unit.schema, unit));
  return `${header(unit.source, stamp)}\n${blocks.map((b) => b.join('\n')).join('\n\n')}\n`;
}

function propType(prop: SpecCatalog['components'][number]['props'][number]): string {
  switch (prop.kind) {
    case 'string':
      return 'string';
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'enum':
      return (prop.enumValues ?? []).map(literal).join(' | ') || 'string';
    case 'array':
      return 'readonly unknown[]';
    default:
      return 'Readonly<Record<string, unknown>>';
  }
}

/**
 * The catalog vocabulary as TypeScript: the closed component ids and the
 * portable props of each component. Platform-extension props are left out:
 * they never come from blueprint data.
 */
export function vocabularyToTypeScript(catalog: SpecCatalog, stamp: Stamp): string {
  const lines = [
    header('catalog/components.json', stamp),
    '/** The built catalog this vocabulary was projected from. */',
    `export const SPEC_CATALOG_HASH = ${literal(catalog.catalogHash)};`,
    '',
    '/** Every closed component id, sorted. */',
    'export const SPEC_COMPONENT_IDS = [',
    ...catalog.components.map((c) => `  ${literal(c.id)},`),
    '] as const;',
    '',
    'export type SpecComponentId = (typeof SPEC_COMPONENT_IDS)[number];',
    '',
    '/** The props a blueprint may set on each component (platform extensions left out). */',
    'export interface SpecComponentProps {',
  ];
  for (const component of catalog.components) {
    const props = component.props.filter((p) => !p.extension);
    if (props.length === 0) {
      lines.push(`  ${key(component.id)}: Record<string, never>;`);
      continue;
    }
    lines.push(`  ${key(component.id)}: {`);
    for (const prop of props) {
      const head = `    ${key(prop.name)}${prop.required ? '' : '?'}:`;
      const type = propType(prop);
      const one = `${head} ${type};`;
      if (one.length <= LINE_WIDTH || prop.kind !== 'enum') {
        lines.push(one);
      } else {
        const members = (prop.enumValues ?? []).map(literal);
        lines.push(
          head,
          ...members.map((m, i) => `      | ${m}${i === members.length - 1 ? ';' : ''}`)
        );
      }
    }
    lines.push('  };');
  }
  lines.push('}', '');
  return lines.join('\n');
}
