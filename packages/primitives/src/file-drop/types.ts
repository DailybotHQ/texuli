import type { Snippet } from 'svelte';
import type { HTMLAttributes } from 'svelte/elements';
import type { ChildSnippet } from '../internal/child.ts';

export type FileDropRejectReason = 'count' | 'size' | 'type';

export interface FileDropRejection {
  file: File;
  reason: FileDropRejectReason;
}

export interface FileDropValidationOptions {
  accept?: string;
  /** Maximum size per file in bytes. */
  maxSize?: number;
  /** Maximum selected file count. */
  maxFiles?: number;
  /** Number of files already selected. */
  currentCount?: number;
  multiple?: boolean;
}

export interface FileDropInputProps extends Record<string, unknown> {
  id: string;
  type: 'file';
  accept?: string;
  multiple?: boolean;
  disabled?: boolean;
  name?: string;
  required?: boolean;
  class?: string;
  'aria-label': string;
  'aria-describedby'?: string;
  'aria-invalid'?: boolean;
  onchange: (event: Event) => void;
}

export interface FileDropValidationResult {
  accepted: File[];
  rejected: FileDropRejection[];
}

export interface FileDropChildState {
  files: readonly File[];
  rejects: readonly FileDropRejection[];
  dragging: boolean;
  disabled: boolean;
  removeFile: (file: File) => void;
}

export type FileDropChildren = Snippet<[FileDropChildState]>;

export type FileDropRootProps = Omit<
  HTMLAttributes<HTMLDivElement>,
  'children' | 'role' | 'ondragenter' | 'ondragover' | 'ondragleave' | 'ondrop'
> & {
  /** Id of the file input (a consumer `<label for>` can name it); generated by default. */
  inputId?: string;
  accept?: string;
  maxSize?: number;
  maxFiles?: number;
  multiple?: boolean;
  disabled?: boolean;
  required?: boolean;
  name?: string;
  files?: File[];
  rejects?: FileDropRejection[];
  label?: string;
  inputLabel?: string;
  browseLabel?: string;
  description?: string;
  inputClass?: string;
  getRejectMessage?: (rejection: FileDropRejection) => string;
  getAnnouncement?: (accepted: readonly File[], rejected: readonly FileDropRejection[]) => string;
  child?: ChildSnippet<FileDropInputProps>;
  children?: FileDropChildren;
};
