/**
 * Generate `src/render-specs.ts`: the lean render specs the player's default
 * catalog is built from (id, label, emit tiers, events, bindable props, and
 * per prop only what validation and painting read: name, kind, required,
 * enum values and a contract `$ref`). The manifests' prose, examples and
 * value schemas stay in the catalog, so the player's eager chunk carries
 * only data it uses.
 *
 *   pnpm exec tsx packages/player/scripts/render-specs.ts           write
 *   pnpm exec tsx packages/player/scripts/render-specs.ts --check   fail on drift
 *
 * `tests/render-specs.test.ts` fails when the committed file drifts from
 * this projection of the live manifests.
 */
import { writeFileSync } from 'node:fs';
import type { CatalogManifest } from '@texuli/catalog/manifest';
import { CHAT_MANIFESTS } from '@texuli/catalog/manifests/chat';
import { COMPOSITION_MANIFESTS } from '@texuli/catalog/manifests/composition';
import { CONTENT_MANIFESTS } from '@texuli/catalog/manifests/content';
import { DATA_MANIFESTS } from '@texuli/catalog/manifests/data';
import { DOCUMENTS_MANIFESTS } from '@texuli/catalog/manifests/documents';
import {
  cardLayoutManifest,
  deckLayoutManifest,
  deckSlideManifest,
  docLayoutManifest,
  gridLayoutManifest,
  pageLayoutManifest,
} from '@texuli/catalog/manifests/layouts';
import { STATE_MANIFESTS } from '@texuli/catalog/manifests/state';
import { WORKFLOWS_MANIFESTS } from '@texuli/catalog/manifests/workflows';
import type { RenderComponentSpec } from '@texuli/catalog/render/renderer';

/** The manifests the player's default catalog holds, in catalog order. */
export const PLAYER_MANIFESTS: readonly CatalogManifest[] = [
  ...CONTENT_MANIFESTS,
  cardLayoutManifest,
  pageLayoutManifest,
  docLayoutManifest,
  gridLayoutManifest,
  deckLayoutManifest,
  deckSlideManifest,
  ...COMPOSITION_MANIFESTS,
  ...STATE_MANIFESTS,
  ...CHAT_MANIFESTS,
  ...DATA_MANIFESTS,
  ...WORKFLOWS_MANIFESTS,
  ...DOCUMENTS_MANIFESTS,
];

export function projectPlayerSpecs(
  manifests: readonly CatalogManifest[] = PLAYER_MANIFESTS
): RenderComponentSpec[] {
  return manifests.map((manifest) => ({
    id: manifest.id,
    label: manifest.label,
    props: manifest.props.map((prop) => ({
      name: prop.name,
      kind: prop.kind,
      ...(prop.required === true ? { required: true } : {}),
      ...(prop.enumValues ? { enumValues: [...prop.enumValues] } : {}),
      ...(prop.schema?.$ref ? { schema: { $ref: prop.schema.$ref } } : {}),
    })),
    agentEmittable: manifest.agentEmittable === true,
    emit: manifest.agentEmittable === true ? ['developer', 'untrusted'] : ['developer'],
    ...(manifest.events ? { events: [...manifest.events] } : {}),
    ...(manifest.bindable ? { bindable: [...manifest.bindable] } : {}),
  }));
}

export function renderSpecsSource(
  specs: readonly RenderComponentSpec[] = projectPlayerSpecs()
): string {
  return `// Generated by packages/player/scripts/render-specs.ts from the catalog
// manifests. Do not edit: run \`pnpm exec tsx packages/player/scripts/render-specs.ts\`.
import type { RenderComponentSpec } from '@texuli/catalog/render/renderer';

/** The lean render specs of the player's default catalog (see the script). */
export const PLAYER_RENDER_SPECS: readonly RenderComponentSpec[] = ${JSON.stringify(specs, null, 2)};
`;
}

export const RENDER_SPECS_FILE = new URL('../src/render-specs.ts', import.meta.url);

if (import.meta.url === `file://${process.argv[1]}`) {
  if (process.argv.includes('--check')) {
    // Compare the data, not the text: the file is Biome-formatted after writing.
    const { PLAYER_RENDER_SPECS } = (await import(RENDER_SPECS_FILE.href)) as {
      PLAYER_RENDER_SPECS: readonly RenderComponentSpec[];
    };
    if (JSON.stringify(PLAYER_RENDER_SPECS) !== JSON.stringify(projectPlayerSpecs())) {
      console.error(
        'src/render-specs.ts is stale: run pnpm exec tsx packages/player/scripts/render-specs.ts'
      );
      process.exit(1);
    }
  } else {
    writeFileSync(RENDER_SPECS_FILE, renderSpecsSource());
    console.log(`src/render-specs.ts: ${projectPlayerSpecs().length} specs (format it with Biome)`);
  }
}
