/**
 * `@texuli/astro/design-system` (ADR-023): server-rendered design systems
 * for Astro. `texuli({ designSystem })` uses these to inline
 * `designSystemStyle` in every page's `<head>` through a generated
 * middleware, so the first paint already has the design system's variables
 * (no flash), and hands the style's SHA-256 to Astro's CSP when it is on.
 * The integration imports this module lazily, only when the option is set.
 */
import {
  type ApplicableDesignSystem,
  type DesignSystemStyleOptions,
  designSystemStyle,
} from '@texuli/tokens/design-system/apply';

export interface TexuliAstroDesignSystem extends DesignSystemStyleOptions {
  /** A compiled design system (`compileDesignSystem`, or a cached JSON copy of one). */
  compiled: ApplicableDesignSystem;
}

/** The attribute that marks the inlined style, so it is added once. */
export const DESIGN_SYSTEM_STYLE_ATTRIBUTE = 'data-tx-ds-style';

/**
 * The CSS to inline and its CSP source (`sha256-…`, without quotes): the
 * SHA-256 of the exact style body, as a CSP `style-src` hash expects.
 */
export async function designSystemInlineStyle(
  input: TexuliAstroDesignSystem
): Promise<{ css: string; hash: `sha256-${string}` }> {
  const css = designSystemStyle(input.compiled, { selector: input.selector, modes: input.modes });
  const digest = new Uint8Array(
    await crypto.subtle.digest('SHA-256', new TextEncoder().encode(css))
  );
  return { css, hash: `sha256-${btoa(String.fromCharCode(...digest))}` };
}

function styleTag(css: string): string {
  // designSystemStyle never emits `<`, so the body cannot close the element.
  if (css.includes('<')) throw new TypeError('The design-system style cannot contain "<".');
  return `<style ${DESIGN_SYSTEM_STYLE_ATTRIBUTE}>${css}</style>`;
}

const HEAD_END = /<\/head\s*>/i;

/** Insert the style before the first `</head>`; a page without one, or already styled, is returned as is. */
export function injectDesignSystemStyle(html: string, css: string): string {
  const tag = styleTag(css);
  const at = html.search(HEAD_END);
  if (at < 0 || html.includes(`<style ${DESIGN_SYSTEM_STYLE_ATTRIBUTE}>`)) return html;
  return `${html.slice(0, at)}${tag}${html.slice(at)}`;
}

/**
 * The source of a self-contained Astro middleware (`onRequest`) that inlines
 * `css` in HTML responses. The integration writes it to Astro's codegen
 * directory; it imports nothing.
 */
export function designSystemMiddlewareSource(css: string): string {
  const tag = JSON.stringify(styleTag(css)).replace(/</g, '\\u003c');
  const marker = JSON.stringify(`<style ${DESIGN_SYSTEM_STYLE_ATTRIBUTE}>`).replace(
    /</g,
    '\\u003c'
  );
  return `// Generated by @texuli/astro (designSystem option). Do not edit.
const tag = ${tag};
const marker = ${marker};
export async function onRequest(_context, next) {
  const response = await next();
  if (!/text\\/html/i.test(response.headers.get('content-type') || '')) return response;
  const html = await response.text();
  const at = html.search(/<\\/head\\s*>/i);
  const headers = new Headers(response.headers);
  headers.delete('content-length');
  const body = at < 0 || html.includes(marker) ? html : html.slice(0, at) + tag + html.slice(at);
  return new Response(body, { status: response.status, statusText: response.statusText, headers });
}
`;
}
