import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { optimizeSvg } from './art-svg.ts';

interface ProvenanceRow {
  id: string;
  shortcode: string;
  name: string;
  source: string;
  sha256: string;
  author: string;
  date: string;
  method: string;
  review: string;
  status: 'reviewed-candidate';
  proposedLicense: string;
}

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const SOURCE = resolve(ROOT, 'artwork/emojis');
const PACKAGE = resolve(ROOT, 'packages/emoji-assets');
const SVG_OUT = resolve(PACKAGE, 'assets/svg');
const PROVENANCE = resolve(SOURCE, 'provenance.json');

function main(): void {
  const provenance = JSON.parse(readFileSync(PROVENANCE, 'utf8')) as {
    schemaVersion: string;
    records: ProvenanceRow[];
  };
  if (provenance.schemaVersion !== 'texuli-emoji-art-provenance/v1')
    throw new Error('unsupported provenance schema');
  mkdirSync(SVG_OUT, { recursive: true });
  const expectedFiles = new Set<string>();
  const manifest = provenance.records.map((record) => {
    if (!/^[0-9a-f]+(?:-[0-9a-f]+)*$/.test(record.id))
      throw new Error(`invalid asset id: ${record.id}`);
    const filename = `${record.id}.svg`;
    if (expectedFiles.has(filename)) throw new Error(`duplicate asset id: ${record.id}`);
    expectedFiles.add(filename);
    const source = readFileSync(resolve(SOURCE, record.source), 'utf8');
    const digest = createHash('sha256').update(source).digest('hex');
    if (digest !== record.sha256)
      throw new Error(`source artwork checksum mismatch for ${record.id}`);
    const optimized = optimizeSvg(source);
    writeFileSync(resolve(SVG_OUT, filename), optimized);
    return {
      id: record.id,
      shortcode: record.shortcode,
      name: record.name,
      path: `./assets/svg/${filename}`,
      sha256: createHash('sha256').update(optimized).digest('hex'),
      width: 64,
      height: 64,
      mimeType: 'image/svg+xml',
      status: record.status,
      proposedLicense: record.proposedLicense,
    };
  });
  for (const filename of readdirSync(SVG_OUT)) {
    if (filename.endsWith('.svg') && !expectedFiles.has(filename))
      throw new Error(`orphan packaged SVG: ${filename}`);
  }
  const lines = [
    '/** Generated by scripts/emojis/build-assets.ts. Do not edit. */',
    "export type EmojiAssetStatus = 'approved' | 'reviewed-candidate';",
    'export interface EmojiAssetRecord {',
    '  readonly id: string;',
    '  readonly shortcode: string;',
    '  readonly name: string;',
    '  readonly path: string;',
    '  readonly sha256: string;',
    '  readonly width: 64;',
    '  readonly height: 64;',
    "  readonly mimeType: 'image/svg+xml';",
    '  readonly status: EmojiAssetStatus;',
    '  readonly proposedLicense: string;',
    '}',
    `const manifestJson = \`${JSON.stringify(manifest, null, 2).replace(/`/g, '\\`').replace(/\$\{/g, '\\${')}\`;`,
    'export const emojiAssetManifest: readonly EmojiAssetRecord[] = JSON.parse(manifestJson);',
    'const byId = new Map(emojiAssetManifest.map((asset) => [asset.id, asset]));',
    'export function getTexuliEmojiAsset(id: unknown): EmojiAssetRecord | undefined {',
    "  if (typeof id !== 'string' || !/^[0-9a-f]+(?:-[0-9a-f]+)*$/.test(id)) return undefined;",
    '  const asset = byId.get(id);',
    "  return asset?.status === 'approved' ? asset : undefined;",
    '}',
    '',
  ];
  writeFileSync(resolve(PACKAGE, 'src/manifest.ts'), lines.join('\n'));
  console.log(`built ${manifest.length} deterministic SVG candidates`);
}

main();
