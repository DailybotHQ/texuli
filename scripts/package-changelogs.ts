/**
 * Generate each published package's CHANGELOG.md from docs/RELEASE.md.
 *
 * The files are never hand-maintained. Rewrite them after editing the release
 * notes; `pnpm verify:packages` checks they match and packs them.
 *
 *     pnpm exec tsx scripts/package-changelogs.ts --write
 *     pnpm exec tsx scripts/package-changelogs.ts --check
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const RELEASE_DOC = 'docs/RELEASE.md';
export const CHANGELOG_FILE = 'CHANGELOG.md';
export const NEVER_PACKED = '@texuli/examples';

const LINE_WIDE =
  /every published package|all \d+ published packages|all \d+ packages|every package moves to|every internal `@texuli\/\*`/i;

const VERSION_HEADING = /^(\d+\.\d+\.\d+)$/;
const PACKAGE_VERSION_HEADING = /^(@texuli\/[a-z0-9-]+|texuli) (\d+\.\d+\.\d+)$/;
const PATCH_TABLE_HEADING = /^0\.8\.x patch releases/;
const SKIP_HEADING = /^(Not on npm|Package changelogs|Known gaps|History|0\.x versioning)\b/;
const TABLE_PACKAGE_ROW = /^\| `(@texuli\/[a-z0-9-]+|texuli)` \| `(\d+\.\d+\.\d+)` \|/;

export interface ReleaseSection {
  heading: string;
  /** Semver heading, or null for the 0.8.x patch table. */
  version: string | null;
  /** Set when the heading names one package. */
  packageName: string | null;
  body: string;
}

export interface PackageChangelog {
  dir: string;
  name: string;
  path: string;
  text: string;
}

/** Banner every generated changelog starts with. */
export function changelogBanner(): string {
  return [
    '# Changelog',
    '',
    'Generated from `docs/RELEASE.md` by `scripts/package-changelogs.ts`. Do not edit this file.',
    '',
  ].join('\n');
}

/**
 * Whether `text` names `packageName`. `texuli` does not match `@texuli/tools`
 * or `texuli.com`.
 */
export function mentionsPackage(text: string, packageName: string): boolean {
  if (packageName === 'texuli') {
    return /(?<!@)\btexuli(?:\/[A-Za-z0-9-]+)?\b(?!\.com)/.test(text);
  }
  const escaped = packageName.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`${escaped}(?![A-Za-z0-9-])`).test(text);
}

export function isLineWide(text: string): boolean {
  return LINE_WIDE.test(text);
}

/** Newest-first numeric compare of `X.Y.Z` versions. */
export function compareVersions(a: string, b: string): number {
  const pa = a.split('.').map((part) => Number.parseInt(part, 10) || 0);
  const pb = b.split('.').map((part) => Number.parseInt(part, 10) || 0);
  const n = Math.max(pa.length, pb.length);
  for (let i = 0; i < n; i += 1) {
    const d = (pa[i] ?? 0) - (pb[i] ?? 0);
    if (d !== 0) return d;
  }
  return 0;
}

/** Version sections under Current npm status, newest first as in the doc. */
export function parseReleaseNotes(markdown: string): ReleaseSection[] {
  const sections: ReleaseSection[] = [];
  const heading = /^### (.+)$/gm;
  const matches = [...markdown.matchAll(heading)];
  for (let i = 0; i < matches.length; i += 1) {
    const match = matches[i];
    if (!match || match.index === undefined) continue;
    const title = match[1]?.trim() ?? '';
    if (SKIP_HEADING.test(title)) {
      if (/^(History|0\.x versioning)\b/.test(title)) break;
      continue;
    }
    const start = match.index + match[0].length;
    const end = matches[i + 1]?.index ?? markdown.length;
    const body = markdown.slice(start, end).replace(/^\n+/, '').replace(/\n+$/, '');
    const versionMatch = VERSION_HEADING.exec(title);
    const packageMatch = PACKAGE_VERSION_HEADING.exec(title);
    if (versionMatch?.[1]) {
      sections.push({ heading: title, version: versionMatch[1], packageName: null, body });
      continue;
    }
    if (packageMatch?.[1] && packageMatch[2]) {
      sections.push({
        heading: title,
        version: packageMatch[2],
        packageName: packageMatch[1],
        body,
      });
      continue;
    }
    if (PATCH_TABLE_HEADING.test(title)) {
      sections.push({ heading: title, version: null, packageName: null, body });
    }
  }
  return sections;
}

function splitChunks(body: string): string[] {
  const lines = body.split('\n');
  const chunks: string[] = [];
  let current: string[] = [];
  const flush = (): void => {
    const text = current.join('\n').trim();
    if (text) chunks.push(text);
    current = [];
  };
  for (const line of lines) {
    if (/^\*\*[^*]/.test(line) && current.length > 0) flush();
    current.push(line);
  }
  flush();
  return chunks;
}

function tableRowVersion(body: string, packageName: string): string | undefined {
  for (const line of body.split('\n')) {
    const row = TABLE_PACKAGE_ROW.exec(line);
    if (row?.[1] === packageName) return row[2];
  }
  return undefined;
}

/** Filtered package table, `undefined` when the chunk is not one. */
function filterTable(chunk: string, packageName: string): string | undefined {
  const lines = chunk.split('\n');
  const tableIdx = lines.findIndex((line) => /^\|/.test(line));
  if (tableIdx < 0) return undefined;
  const header = lines[tableIdx] ?? '';
  if (!/package/i.test(header)) return undefined;
  const sep = lines[tableIdx + 1] ?? '';
  const rows: string[] = [];
  let i = tableIdx + 2;
  for (; i < lines.length; i += 1) {
    const line = lines[i] ?? '';
    if (!/^\|/.test(line)) break;
    if (mentionsPackage(line, packageName)) rows.push(line);
  }
  const before = lines.slice(0, tableIdx).join('\n').trim();
  const after = lines.slice(i).join('\n').trim();
  const parts: string[] = [];
  if (before) parts.push(before);
  if (rows.length > 0) parts.push([header, sep, ...rows].join('\n'));
  if (after && mentionsPackage(after, packageName)) parts.push(after);
  return parts.join('\n\n');
}

function selectChunks(
  body: string,
  packageName: string,
  options: { keepLineWideIntro: boolean; keepAll: boolean }
): string {
  if (options.keepAll) return body.trim();
  const chunks = splitChunks(body);
  const kept: string[] = [];
  for (let i = 0; i < chunks.length; i += 1) {
    const chunk = chunks[i] ?? '';
    const table = filterTable(chunk, packageName);
    if (table !== undefined) {
      if (table.length > 0) kept.push(table);
      continue;
    }
    if (i === 0 && options.keepLineWideIntro && isLineWide(chunk)) {
      kept.push(chunk);
      continue;
    }
    if (mentionsPackage(chunk, packageName)) kept.push(chunk);
  }
  return kept.join('\n\n').trim();
}

function firstMentionedVersion(
  sections: readonly ReleaseSection[],
  packageName: string
): string | null {
  let first: string | null = null;
  for (const section of sections) {
    const version = section.version ?? tableRowVersion(section.body, packageName);
    if (!version) continue;
    const mentioned =
      section.packageName === packageName || mentionsPackage(section.body, packageName);
    if (!mentioned) continue;
    if (first === null || compareVersions(version, first) < 0) first = version;
  }
  return first;
}

function sectionVersion(section: ReleaseSection, packageName: string): string | undefined {
  return section.version ?? tableRowVersion(section.body, packageName);
}

function includeSection(
  section: ReleaseSection,
  packageName: string,
  firstMention: string | null
): boolean {
  if (section.packageName) return section.packageName === packageName;
  const version = sectionVersion(section, packageName);
  if (!version) return false;
  if (mentionsPackage(section.body, packageName)) return true;
  if (!section.version) return false;
  if (!isLineWide(section.body)) return false;
  if (firstMention === null) return true;
  return compareVersions(section.version, firstMention) >= 0;
}

/** One package's changelog body, generated from the release notes. */
export function changelogForPackage(packageName: string, markdown: string): string {
  const sections = parseReleaseNotes(markdown);
  const firstMention = firstMentionedVersion(sections, packageName);
  const byVersion = new Map<string, string[]>();
  for (const section of sections) {
    if (!includeSection(section, packageName, firstMention)) continue;
    const version = sectionVersion(section, packageName);
    if (!version) continue;
    const text = selectChunks(section.body, packageName, {
      keepLineWideIntro: section.packageName === null && isLineWide(section.body),
      keepAll: section.packageName === packageName,
    });
    if (!text) continue;
    const list = byVersion.get(version) ?? [];
    list.push(text);
    byVersion.set(version, list);
  }
  const versions = [...byVersion.keys()].sort((a, b) => compareVersions(b, a));
  const parts = [changelogBanner().trimEnd()];
  for (const version of versions) {
    const body = (byVersion.get(version) ?? []).join('\n\n').trim();
    if (!body) continue;
    parts.push('', `## ${version}`, '', body);
  }
  return `${parts.join('\n')}\n`;
}

interface WorkspacePkg {
  dir: string;
  name: string;
}

function publishedPackages(root: string): WorkspacePkg[] {
  const dir = join(root, 'packages');
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && existsSync(join(dir, entry.name, 'package.json')))
    .map((entry) => {
      const manifest = JSON.parse(readFileSync(join(dir, entry.name, 'package.json'), 'utf8')) as {
        name?: string;
      };
      return { dir: entry.name, name: String(manifest.name ?? '') };
    })
    .filter((pkg) => pkg.name !== NEVER_PACKED)
    .sort((a, b) => a.dir.localeCompare(b.dir));
}

/** Generated changelog for every published package under `root`. */
export function packageChangelogs(root: string = ROOT): PackageChangelog[] {
  const markdown = readFileSync(join(root, RELEASE_DOC), 'utf8');
  return publishedPackages(root).map((pkg) => ({
    dir: pkg.dir,
    name: pkg.name,
    path: join('packages', pkg.dir, CHANGELOG_FILE),
    text: changelogForPackage(pkg.name, markdown),
  }));
}

/** Drift between committed CHANGELOG.md files and docs/RELEASE.md. */
export function changelogDrift(root: string = ROOT): string[] {
  const problems: string[] = [];
  for (const pkg of packageChangelogs(root)) {
    const file = join(root, pkg.path);
    if (!existsSync(file)) {
      problems.push(
        `${pkg.path}: missing (run pnpm exec tsx scripts/package-changelogs.ts --write)`
      );
      continue;
    }
    const have = readFileSync(file, 'utf8');
    if (have === pkg.text) continue;
    const a = have.split('\n');
    const b = pkg.text.split('\n');
    let line = 0;
    while (line < Math.max(a.length, b.length) && a[line] === b[line]) line += 1;
    problems.push(
      `${pkg.path}:${line + 1} differs from docs/RELEASE.md\n    committed: ${JSON.stringify(a[line] ?? '(end of file)')}\n    generated: ${JSON.stringify(b[line] ?? '(end of file)')}`
    );
  }
  return problems;
}

export function writePackageChangelogs(root: string = ROOT): PackageChangelog[] {
  const files = packageChangelogs(root);
  for (const pkg of files) {
    const file = join(root, pkg.path);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, pkg.text);
  }
  return files;
}

function main(argv: readonly string[]): number {
  const check = argv.includes('--check') || !argv.includes('--write');
  if (check && argv.includes('--write')) {
    console.error('Use either --write or --check');
    return 2;
  }
  if (argv.includes('--write')) {
    const files = writePackageChangelogs();
    for (const pkg of files) console.log(`wrote ${pkg.path}`);
    return 0;
  }
  const drift = changelogDrift();
  if (drift.length === 0) {
    console.log(`package-changelogs ✓ ${packageChangelogs().length} files match docs/RELEASE.md`);
    return 0;
  }
  console.error(`package-changelogs ✗ ${drift.length} file(s) drifted from docs/RELEASE.md:`);
  for (const problem of drift) console.error(`  ${problem}`);
  console.error('Regenerate with: pnpm exec tsx scripts/package-changelogs.ts --write');
  return 1;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
