/**
 * The generated agent surfaces (ADR-017, T-surfaces-sync): pure builders that
 * turn the operations registry of `@texuli/tools/ops`, the MCP handler and
 * the remote endpoint's limits into
 *
 * - the MCP server card (`apps/website/public/.well-known/mcp/server-card.json`);
 * - the "Tools" section of the site `llms.txt` (through `generate-site-llms.ts`);
 * - the operations tables of `packages/tools/docs/ops.md` (between markers);
 * - the data module of the `/mcp-server/` page
 *   (`apps/website/src/components/mcp-server/mcp-server-data.ts`).
 *
 * Nothing here writes; `scripts/generate-surfaces.ts` writes the files and
 * `pnpm check:surfaces` fails when a committed file differs. Generated files
 * are never edited by hand.
 */
import {
  MCP_BATCH_MAX,
  MCP_BODY_MAX,
  MCP_CALL_TIMEOUT_MS,
  MCP_RATE_POLICY,
} from '../functions/_lib/mcp-endpoint.ts';
import { createMcpHandler } from '../packages/tools/src/mcp/handler.ts';
import { TEXULI_PROMPTS } from '../packages/tools/src/mcp/prompts.ts';
import {
  MCP_PROTOCOL_VERSION,
  MCP_SUPPORTED_PROTOCOL_VERSIONS,
} from '../packages/tools/src/mcp/protocol.ts';
import { texuliResources } from '../packages/tools/src/mcp/resources.ts';
import { MCP_STDIO_MAX_MESSAGE_BYTES } from '../packages/tools/src/mcp/stdio.ts';
import {
  LOCAL_RUNTIMES,
  type Operation,
  type OperationRegistry,
  REMOTE_RUNTIMES,
  TOOLS_VERSION,
  texuliOps,
} from '../packages/tools/src/ops/index.ts';

export const SITE_ORIGIN = 'https://texuli.com';
export const REMOTE_MCP_URL = `${SITE_ORIGIN}/mcp`;
export const LOCAL_MCP_LAUNCH = 'npx -y @texuli/mcp';
export const SERVER_CARD_PATH = '/.well-known/mcp/server-card.json';
const REPO = 'https://github.com/DailybotHQ/texuli';
export const MCP_DOCS_URL = `${REPO}/blob/main/packages/tools/docs/mcp.md`;
export const OPS_DOCS_URL = `${REPO}/blob/main/packages/tools/docs/ops.md`;

const GENERATED_NOTE =
  'Generated by scripts/generate-surfaces.ts from the @texuli/tools operations registry; do not edit. pnpm check:surfaces fails on drift.';

/** Whether the remote endpoint serves an operation (`edge` and `site`, ADR-018). */
export function servedRemotely(operation: Operation): boolean {
  return REMOTE_RUNTIMES.includes(operation.runtime);
}

/** Whether the local doors (stdio MCP, CLI) serve an operation (`edge` and `node`). */
export function servedLocally(operation: Operation): boolean {
  return LOCAL_RUNTIMES.includes(operation.runtime);
}

/** Which doors serve an operation, in words. */
function doorsOf(operation: Operation): string {
  if (!servedLocally(operation)) return 'Remote only (reads the built texuli.com).';
  return servedRemotely(operation) ? 'Local and remote.' : 'Local only (needs Node).';
}

/** Every tool name a door lists: its operations, then the aliases whose targets it serves. */
export function toolNames(
  registry: OperationRegistry,
  runtimes?: readonly ('edge' | 'node' | 'site')[]
): string[] {
  const served = registry.list(runtimes ? { runtimes } : {}).map((operation) => operation.name);
  const set = new Set(served);
  for (const alias of registry.aliases())
    if (alias.targets.every((target) => set.has(target))) served.push(alias.name);
  return served;
}

/** The capabilities the handler advertises, as flat names, from a real `initialize`. */
export async function advertisedCapabilities(): Promise<string[]> {
  const handler = createMcpHandler({ mode: 'stateless', runtimes: REMOTE_RUNTIMES });
  const response = (await handler({
    jsonrpc: '2.0',
    id: 1,
    method: 'initialize',
    params: {
      protocolVersion: MCP_PROTOCOL_VERSION,
      capabilities: {},
      clientInfo: { name: 'generate-surfaces', version: '0' },
    },
  })) as { result?: { capabilities?: Record<string, unknown> } } | undefined;
  const capabilities = response?.result?.capabilities;
  if (!capabilities) throw new Error('The MCP handler did not answer initialize.');
  return Object.keys(capabilities);
}

/** The MCP server card the site publishes. */
export async function buildServerCard(registry: OperationRegistry = texuliOps) {
  const operations = registry.list();
  const remote = new Set(toolNames(registry, REMOTE_RUNTIMES));
  return {
    $comment: GENERATED_NOTE,
    serverInfo: {
      name: 'texuli',
      title: 'Texuli MCP Server',
      version: TOOLS_VERSION,
      description: `Every Texuli operation as an MCP tool: search the component catalog, read manifests and examples, validate manifests and blueprints, search, read and preview themes, and run deck and document commands. Local over stdio (${LOCAL_MCP_LAUNCH}, the edge and node operations) or remote over Streamable HTTP (${REMOTE_MCP_URL}, the edge operations plus the site operations that list, read and search texuli.com's pages as Markdown). Read-only: nothing is stored, fetched from the network or modified.`,
      documentation: MCP_DOCS_URL,
    },
    protocolVersion: MCP_PROTOCOL_VERSION,
    protocolVersions: [...MCP_SUPPORTED_PROTOCOL_VERSIONS],
    transport: {
      streamableHttp: {
        url: REMOTE_MCP_URL,
        stateless: true,
        responses: 'application/json',
        authentication: 'none',
        operations: 'edge, site',
        limits: {
          bodyBytes: MCP_BODY_MAX,
          batch: MCP_BATCH_MAX,
          callTimeoutMs: MCP_CALL_TIMEOUT_MS,
          ratePerMinute: Math.round(
            (MCP_RATE_POLICY.capacity * 60) / MCP_RATE_POLICY.windowSeconds
          ),
        },
      },
      stdio: {
        launch: LOCAL_MCP_LAUNCH,
        package: '@texuli/mcp',
        authentication: 'none',
        operations: 'edge, node',
        limits: { messageBytes: MCP_STDIO_MAX_MESSAGE_BYTES },
      },
    },
    capabilities: await advertisedCapabilities(),
    tools: operations.map((operation) => ({
      name: operation.name,
      title: operation.title,
      description: operation.summary,
      runtime: operation.runtime,
      remote: remote.has(operation.name),
      local: servedLocally(operation),
      readOnly: operation.annotations.readOnly,
    })),
    deprecatedTools: registry.aliases().map((alias) => ({
      name: alias.name,
      replacedBy: [...alias.targets],
      removeIn: alias.removeIn,
      remote: remote.has(alias.name),
    })),
    removedTools: registry.removed().map((entry) => ({
      name: entry.name,
      replacedBy: [...entry.replacedBy],
      removedIn: entry.removedIn,
    })),
  };
}

/** The "Tools" section of the site llms.txt. */
export function toolsLlmsSection(
  siteUrl: string = SITE_ORIGIN,
  registry: OperationRegistry = texuliOps
) {
  return {
    name: 'Tools',
    description: `Every Texuli operation is an MCP tool and a texuli CLI command (texuli <group> <verb>), from one registry. Local MCP: ${LOCAL_MCP_LAUNCH} over stdio, the edge and node operations. Remote MCP: Streamable HTTP POST to ${REMOTE_MCP_URL}, the edge operations plus site.pages, site.read and site.search (texuli.com's pages as Markdown; remote only). Read-only; no account or key.`,
    links: [
      {
        title: 'MCP server card',
        href: `${siteUrl}${SERVER_CARD_PATH}`,
        description: 'Transports, protocol versions, capabilities and every tool, as JSON.',
      },
      ...registry.list().map((operation) => ({
        title: operation.name,
        href: `${OPS_DOCS_URL}#operations`,
        description: `${operation.title}. ${operation.summary} ${doorsOf(operation)}`,
      })),
    ],
  };
}

const cell = (text: string) => text.replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');
const number = (value: number) => value.toLocaleString('en-US');

/** The generated operation tables of `packages/tools/docs/ops.md` (between the markers). */
export function buildOpsTables(registry: OperationRegistry = texuliOps): string {
  const operations = registry.list();
  const lines = [
    '| Name | Title | Runtime | Doors | CLI | Summary |',
    '| --- | --- | --- | --- | --- | --- |',
    ...operations.map((operation) => {
      const [group, verb] = [
        operation.name.slice(0, operation.name.indexOf('.')),
        operation.name.slice(operation.name.indexOf('.') + 1),
      ];
      const doors = !servedLocally(operation)
        ? 'remote MCP only'
        : servedRemotely(operation)
          ? 'local and remote MCP, CLI'
          : 'local MCP, CLI';
      const cli = servedLocally(operation) ? `\`texuli ${group} ${verb}\`` : '—';
      return `| \`${operation.name}\` | ${cell(operation.title)} | ${operation.runtime} | ${doors} | ${cli} | ${cell(operation.summary)} |`;
    }),
    '',
    '### Limits',
    '',
    '| Name | Input bytes | Items | Time budget | Arguments |',
    '| --- | --- | --- | --- | --- |',
    ...operations.map((operation) => {
      const properties = Object.keys((operation.input.properties ?? {}) as object);
      const required = new Set((operation.input.required as string[] | undefined) ?? []);
      const args = properties
        .map((key) => `\`${key}\`${required.has(key) ? ' (required)' : ''}`)
        .join(', ');
      return `| \`${operation.name}\` | ${number(operation.limits.inputBytes)} | ${operation.limits.items === undefined ? '—' : number(operation.limits.items)} | ${number(operation.limits.timeMs / 1000)} s | ${args || '—'} |`;
    }),
    '',
    ...(registry.aliases().length === 0
      ? []
      : [
          '### Deprecated tool names',
          '',
          '| Alias | Resolves to | Removed in |',
          '| --- | --- | --- |',
          ...registry
            .aliases()
            .map(
              (alias) =>
                `| \`${alias.name}\` | ${alias.targets.map((target) => `\`${target}\``).join(', ')} | \`${alias.removeIn}\` |`
            ),
          '',
        ]),
    '### Removed tool names',
    '',
    'A call to a removed name is refused with a message that names the operation to call instead.',
    '',
    '| Name | Call instead | Removed in |',
    '| --- | --- | --- |',
    ...registry
      .removed()
      .map(
        (entry) =>
          `| \`${entry.name}\` | ${entry.replacedBy.map((target) => `\`${target}\``).join(', ')} | \`${entry.removedIn}\` |`
      ),
  ];
  return lines.join('\n');
}

export const OPS_MARKER_START =
  '<!-- surfaces:operations:start (generated by scripts/generate-surfaces.ts; do not edit) -->';
export const OPS_MARKER_END = '<!-- surfaces:operations:end -->';

/** `ops.md` with the generated block replaced; throws when the markers are missing. */
export function spliceOpsDoc(markdown: string, tables: string): string {
  const start = markdown.indexOf(OPS_MARKER_START);
  const end = markdown.indexOf(OPS_MARKER_END);
  if (start < 0 || end < start)
    throw new Error('packages/tools/docs/ops.md has no surfaces:operations markers.');
  return `${markdown.slice(0, start + OPS_MARKER_START.length)}\n\n${tables}\n\n${markdown.slice(end)}`;
}

/** The data the `/mcp-server/` page renders: tools, resources, prompts and limits. */
export async function buildMcpPageData(registry: OperationRegistry = texuliOps) {
  const card = await buildServerCard(registry);
  const perItem = /^texuli:\/\/(?:component|docs|theme)\//u;
  const resources = (await texuliResources.list()).filter(
    (resource) => !perItem.test(resource.uri)
  );
  return {
    version: TOOLS_VERSION,
    protocolVersion: MCP_PROTOCOL_VERSION,
    protocolVersions: [...MCP_SUPPORTED_PROTOCOL_VERSIONS],
    remote: { url: REMOTE_MCP_URL, ...card.transport.streamableHttp.limits },
    local: { launch: LOCAL_MCP_LAUNCH, messageBytes: MCP_STDIO_MAX_MESSAGE_BYTES },
    serverCard: SERVER_CARD_PATH,
    capabilities: card.capabilities,
    tools: registry.list().map((operation) => {
      const properties = (operation.input.properties ?? {}) as Record<
        string,
        { description?: unknown }
      >;
      const required = new Set((operation.input.required as string[] | undefined) ?? []);
      return {
        name: operation.name,
        title: operation.title,
        summary: operation.summary,
        runtime: operation.runtime,
        remote: servedRemotely(operation),
        local: servedLocally(operation),
        limits: { ...operation.limits },
        arguments: Object.entries(properties).map(([name, schema]) => ({
          name,
          required: required.has(name),
          description: typeof schema.description === 'string' ? schema.description : '',
        })),
        example: operation.examples[0]?.title ?? '',
      };
    }),
    deprecatedTools: card.deprecatedTools,
    removedTools: card.removedTools,
    resources: resources.map((resource) => ({
      uri: resource.uri,
      title: resource.title ?? resource.name,
      description: resource.description,
      mimeType: resource.mimeType,
    })),
    resourceTemplates: texuliResources.templates.map((template) => ({
      uriTemplate: template.uriTemplate,
      title: template.title ?? template.name,
      description: template.description,
      mimeType: template.mimeType,
    })),
    prompts: TEXULI_PROMPTS.map((prompt) => ({
      name: prompt.name,
      title: prompt.title,
      description: prompt.description,
      arguments: prompt.arguments.map((argument) => ({
        name: argument.name,
        required: argument.required === true,
        description: argument.description,
        ...(argument.enum ? { enum: [...argument.enum] } : {}),
      })),
    })),
  };
}

/** The `/mcp-server/` data module source (TypeScript, one exported constant). */
export async function buildMcpPageModule(registry: OperationRegistry = texuliOps): Promise<string> {
  const data = await buildMcpPageData(registry);
  return `/**\n * The /mcp-server/ page data. ${GENERATED_NOTE}\n */\nexport const MCP_SERVER_DATA = ${JSON.stringify(data, null, 2)} as const;\n`;
}
