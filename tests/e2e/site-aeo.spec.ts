/// <reference types="node" />

import { createHash } from 'node:crypto';
import { createReadStream, existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { createServer, type Server } from 'node:http';
import type { AddressInfo } from 'node:net';
import { extname, join, normalize, relative, resolve } from 'node:path';
import { expect, test } from '@playwright/test';
import { isDocsPath } from '../../apps/website/src/components/foundation/nav-data.ts';
import { buildSiteLlmsTxt, SITE_URL } from '../../scripts/generate-site-llms.ts';

/*
 * texuli.com AEO (T-22): the physical root llms.txt. The file is committed
 * (public/llms.txt, generated by scripts/generate-site-llms.ts), served with
 * zero redirects, and must never drift from the nav data it is generated
 * from. Served from apps/website/dist like a static host.
 */

const DIST = resolve('apps/website/dist');
const SITE = SITE_URL;
const TYPES: Record<string, string> = {
  '.html': 'text/html; charset=utf-8',
  '.txt': 'text/plain; charset=utf-8',
  '.json': 'application/json',
  '.md': 'text/markdown; charset=utf-8',
};

let server: Server;
let origin = '';

test.beforeAll(async () => {
  if (!existsSync(join(DIST, 'index.html'))) throw new Error('Run `pnpm build` before this spec.');
  server = createServer((request, response) => {
    const path = decodeURIComponent(new URL(request.url ?? '/', 'http://site').pathname);
    let file = normalize(join(DIST, path));
    if (!file.startsWith(DIST)) file = join(DIST, '__outside__');
    if (existsSync(file) && statSync(file).isDirectory()) file = join(file, 'index.html');
    if (!existsSync(file)) {
      response.writeHead(404, { 'content-type': TYPES['.html'] });
      createReadStream(join(DIST, '404.html')).pipe(response);
      return;
    }
    response.writeHead(200, { 'content-type': TYPES[extname(file)] ?? 'application/octet-stream' });
    createReadStream(file).pipe(response);
  });
  await new Promise<void>((done) => server.listen(0, '127.0.0.1', done));
  origin = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
});
test.afterAll(() => new Promise<void>((done) => server.close(() => done())));

/**
 * The llms.txt as the generator would build it right now: its own exported
 * config (T-100 P2-5), never a hand copy of the title, summary or intro.
 */
function currentLlmsTxt(): string {
  return buildSiteLlmsTxt(SITE);
}

/** Whether a site URL exists in the build (files first, then directory HTML). */
function builtPath(url: string): string | null {
  if (!url.startsWith(`${SITE}/`)) return null;
  const path = url.slice(SITE.length);
  const file = normalize(join(DIST, path));
  if (!file.startsWith(DIST)) return null;
  if (existsSync(file) && statSync(file).isFile()) return file;
  const dirIndex = join(file, 'index.html');
  return existsSync(dirIndex) ? dirIndex : null;
}

test.describe('root llms.txt', () => {
  test('is served physically: plain text, no redirect stub, exactly what the generator emits', async ({
    request,
  }) => {
    const response = await request.get(`${origin}/llms.txt`);
    expect(response.status()).toBe(200);
    expect(response.headers()['content-type']).toBe('text/plain; charset=utf-8');
    const body = await response.text();
    // A redirect stub would be HTML (Astro emits a meta-refresh page); the
    // physical file is the real index.
    expect(body.startsWith('# Texuli\n\n> ')).toBe(true);
    expect(body).not.toContain('<html');
    expect(body).toBe(currentLlmsTxt());
  });

  test('lists every site area and only routes that exist in the build', () => {
    const body = readFileSync(join(DIST, 'llms.txt'), 'utf8');
    for (const area of ['Guides', 'Components', 'Primitives', 'Themes', 'Agents', 'Project'])
      expect(body, `section for ${area}`).toContain(`## ${area}\n`);
    const hrefs = [...body.matchAll(/^- \[[^\]]+\]\((https:\/\/texuli\.com[^)]*)\)/gm)].map(
      (match) => match[1]
    );
    expect(hrefs.length).toBeGreaterThan(30);
    for (const href of hrefs) {
      const path = href.slice(SITE.length);
      const direct = join(DIST, path);
      const file =
        path === '/'
          ? join(DIST, 'index.html')
          : existsSync(direct) && !statSync(direct).isDirectory()
            ? direct
            : join(DIST, path, 'index.html');
      expect(existsSync(file), href).toBe(true);
    }
  });

  test('the agent catalog files it links stay served', async ({ request }) => {
    for (const path of ['/llms/llms.txt', '/llms/llms-full.txt', '/catalog/catalog.json']) {
      const response = await request.get(`${origin}${path}`);
      expect(response.status(), path).toBe(200);
    }
  });
});

test.describe('markdown twins (docs pages)', () => {
  /** Every built docs-class page (`/guides/…`, `/component-pages/…`, …). */
  function docsPages(): string[] {
    const pages: string[] = [];
    const walk = (dir: string) => {
      for (const entry of readdirSync(dir, { withFileTypes: true })) {
        const full = join(dir, entry.name);
        if (entry.isDirectory()) walk(full);
        else if (entry.name === 'index.html' && isDocsPath(`/${relative(DIST, dir)}/`))
          pages.push(`/${relative(DIST, dir)}/`);
      }
    };
    walk(DIST);
    return pages.sort();
  }

  test('every docs page has a markdown twin beside its HTML', () => {
    const pages = docsPages();
    expect(pages.length).toBeGreaterThan(50);
    const missing = pages.filter((path) => !existsSync(join(DIST, `${path.slice(0, -1)}.md`)));
    expect(missing, `twins missing for ${missing.length} of ${pages.length}`).toEqual([]);
  });

  test('the manifest records exactly the built twins', () => {
    const manifest = JSON.parse(readFileSync(join(DIST, 'md-manifest.json'), 'utf8')) as {
      twins: Record<string, string>;
    };
    const pages = docsPages();
    expect(Object.keys(manifest.twins).sort()).toEqual(pages);
    for (const [path, md] of Object.entries(manifest.twins))
      expect(md).toBe(`${path.slice(0, -1)}.md`);
  });

  for (const path of [
    '/guides/theming/',
    '/guides/why-svelte-kotlin/',
    '/component-pages/button/',
    '/primitives-page/accordion/',
    '/skill/',
  ]) {
    test(`the twin of ${path} is clean markdown: h1, fences, absolute links, no HTML`, async ({
      request,
    }) => {
      const response = await request.get(`${origin}${path.slice(0, -1)}.md`);
      expect(response.status()).toBe(200);
      expect(response.headers()['content-type']).toBe('text/markdown; charset=utf-8');
      const body = await response.text();
      expect(body.startsWith('# ')).toBe(true);
      expect(body, 'a source line naming the page URL').toContain(`Source: ${SITE}${path}`);
      // Headings survived and code fences are balanced; links, when the page
      // has any, are absolute (or in-page anchors).
      expect(body).toMatch(/^## /m);
      expect((body.match(/```/g) ?? []).length % 2).toBe(0);
      for (const href of [...body.matchAll(/\]\(([^)]+)\)/g)].map((match) => match[1]))
        expect(href.startsWith('/') && !href.startsWith('//'), href).toBe(false);
      // No HTML tags outside code fences.
      const outsideFences = body.split(/```[\s\S]*?```/g).join('');
      expect(outsideFences).not.toMatch(
        /<\/?(?:div|span|p|a|script|style|table|button|svg|img|template|pre|code)\b/i
      );
    });
  }

  test('every component page twin matches a component doc, and props tables are well-formed', () => {
    const manifest = JSON.parse(readFileSync(join(DIST, 'md-manifest.json'), 'utf8')) as {
      twins: Record<string, string>;
    };
    const componentTwins = Object.keys(manifest.twins)
      .filter((path) => /^\/component-pages\/[^/]+\/$/.test(path))
      .map((path) => path.replace('/component-pages', ''))
      .sort();
    const llmsIds = readdirSync(join(DIST, 'llms/components'))
      .filter((file) => file.endsWith('.md'))
      .map((file) => `/${file.slice(0, -3)}/`)
      .sort();
    expect(componentTwins.length).toBeGreaterThan(100);
    expect(componentTwins).toEqual(llmsIds);
    // Tables are well-formed: every separator row follows its header row —
    // a separator after another separator is the th-row bug (this page has
    // Props and Keyboard tables, each with one separator).
    const button = readFileSync(join(DIST, 'component-pages/button.md'), 'utf8');
    const lines = button.split('\n');
    const doubled = lines.filter(
      (line, index) => /^\| --- /.test(line) && /^\| --- /.test(lines[index - 1] ?? '')
    );
    expect(doubled).toEqual([]);
    expect((button.match(/^\| --- /gm) ?? []).length).toBeGreaterThanOrEqual(1);
  });
});

test.describe('.well-known agent discovery (T-25)', () => {
  /** The four discovery documents, served and parsed. */
  function fetchWellKnown() {
    const read = (path: string) => JSON.parse(readFileSync(join(DIST, path), 'utf8')) as never;
    return {
      aiCatalog: read('.well-known/ai-catalog.json') as {
        host: { displayName: string; documentationUrl: string; logoUrl: string };
        entries: { identifier: string; url: string; type: string }[];
      },
      apiCatalog: read('.well-known/api-catalog') as {
        linkset: { anchor: string; links: { rel: string; href: string }[] }[];
      },
      serverCard: read('.well-known/mcp/server-card.json') as {
        serverInfo: { name: string; version: string };
        transport: { stdio: { launch: string } };
        capabilities: string[];
        tools: string[];
      },
      skillIndex: read('.well-known/agent-skills/index.json') as {
        skills: { name: string; url: string; digest: string }[];
      },
    };
  }

  test('the quartet exists, parses and describes only real surfaces', () => {
    const { aiCatalog, apiCatalog, serverCard } = fetchWellKnown();
    expect(aiCatalog.host.displayName).toBe('Texuli');
    expect(aiCatalog.entries.length).toBeGreaterThanOrEqual(6);
    const identifiers = aiCatalog.entries.map((entry) => entry.identifier);
    expect(new Set(identifiers).size).toBe(identifiers.length);
    // Every texuli.com URL in the ARD and the linkset resolves in the build;
    // the only off-site host allowed is the npm registry.
    for (const url of [
      ...aiCatalog.entries.map((entry) => entry.url),
      ...apiCatalog.linkset.flatMap((set) => set.links.map((link) => link.href)),
    ]) {
      if (!url.startsWith(`${SITE}/`)) {
        expect(url, 'off-site ARD URLs').toMatch(/^https:\/\/www\.npmjs\.com\//);
        continue;
      }
      expect(builtPath(url), url).not.toBeNull();
    }
    // The server card describes the real stdio surface: the five shipped
    // tools, launched from the tools package source, no hosted endpoint.
    expect(serverCard.serverInfo.name).toBe('texuli');
    expect(new Set(serverCard.tools)).toEqual(
      new Set(['catalog', 'component', 'validate', 'example', 'theme'])
    );
    expect(serverCard.capabilities).toContain('tools');
    expect(serverCard.transport.stdio.launch).toContain('tsx src/mcp/stdio.ts');
    expect(JSON.stringify(serverCard)).not.toContain('"streamableHttp"');
  });

  test('the documentation URLs the ARD host and the skill pack advertise are built routes', () => {
    const { aiCatalog } = fetchWellKnown();
    // T-100 P1-4: https://texuli.com/docs/ was advertised but has no route.
    for (const url of [aiCatalog.host.documentationUrl, aiCatalog.host.logoUrl])
      expect(builtPath(url), url).not.toBeNull();
    const skillPack = join(DIST, 'skill-pack');
    const skillFiles = (dir: string): string[] =>
      readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
        entry.isDirectory()
          ? skillFiles(join(dir, entry.name))
          : entry.name === 'SKILL.md'
            ? [join(dir, entry.name)]
            : []
      );
    const files = skillFiles(skillPack);
    expect(files.length).toBeGreaterThanOrEqual(6);
    for (const file of files) {
      const head = readFileSync(file, 'utf8').split('\n---', 1)[0] ?? '';
      const urls = [...head.matchAll(/^\s*(?:documentation_url|homepage):\s*(\S+)\s*$/gm)].map(
        (match) => match[1] as string
      );
      expect(urls.length, `${relative(DIST, file)} names its documentation URL`).toBe(2);
      for (const url of urls)
        expect(builtPath(url), `${relative(DIST, file)}: ${url}`).not.toBeNull();
    }
  });

  test('the agent-skills index digests match the served skill pack', () => {
    const { skillIndex } = fetchWellKnown();
    expect(skillIndex.skills.length).toBeGreaterThanOrEqual(6);
    for (const skill of skillIndex.skills) {
      const file = builtPath(skill.url);
      expect(file, skill.url).not.toBeNull();
      expect(
        createHash('sha256')
          .update(readFileSync(file as string))
          .digest('hex')
      ).toBe(skill.digest.replace(/^sha256:/, ''));
    }
  });

  test('the quartet is served with the right status from the static host', async ({ request }) => {
    for (const path of [
      '/.well-known/ai-catalog.json',
      '/.well-known/api-catalog',
      '/.well-known/mcp/server-card.json',
      '/.well-known/agent-skills/index.json',
      '/skill-pack/SKILL.md',
      '/skill-pack/SHA256SUMS',
    ]) {
      const response = await request.get(`${origin}${path}`);
      expect(response.status(), path).toBe(200);
    }
  });
});
