/**
 * Renders `apps/website/docs/illustration-prompts.md` from the illustration
 * manifest (`apps/website/src/data/illustrations.json`): one self-contained
 * image-generation prompt per slot, with its file name, size and page. Never
 * edit the doc by hand; edit the manifest and rerun.
 *
 * Usage:
 *   pnpm exec tsx apps/website/scripts/illustration-prompts.ts           # write
 *   pnpm exec tsx apps/website/scripts/illustration-prompts.ts --check   # exit 1 on drift
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { ILLUSTRATIONS, type IllustrationEntry } from '../src/components/landing/illustrations.ts';

export const PROMPTS_DOC = resolve(import.meta.dirname, '../docs/illustration-prompts.md');

const USE: Record<IllustrationEntry['variant'], string> = {
  plate: 'landing plate',
  band: 'landing band',
  banner: 'page banner',
};

/** The prompts doc for a manifest, deterministic for a given input. */
export function renderPromptsDoc(entries: readonly IllustrationEntry[]): string {
  const lines = [
    '# Illustration prompts',
    '',
    '<!-- Generated by apps/website/scripts/illustration-prompts.ts from',
    '     apps/website/src/data/illustrations.json. Do not edit by hand. -->',
    '',
    `One self-contained prompt per illustration slot (${entries.length} slots). Each prompt`,
    'carries the whole style from [ILLUSTRATIONS.md](ILLUSTRATIONS.md), so it can be',
    'handed to an image-generation agent on its own. Save each result as the named',
    'WebP file, at the exact size, in `apps/website/public/illustrations/`; the slot',
    'switches from its texel fallback to the file on the next build. A dark variant',
    'is optional.',
    '',
    '| Slot | File | Size | Use |',
    '| --- | --- | --- | --- |',
    ...entries.map(
      (entry) =>
        `| \`${entry.slot}\` | \`${entry.file}\`${entry.fileDark ? ` (dark: \`${entry.fileDark}\`)` : ''} | ${entry.width}×${entry.height} | ${USE[entry.variant]} |`
    ),
  ];
  for (const entry of entries) {
    lines.push(
      '',
      `## ${entry.slot}`,
      '',
      `- File: \`${entry.file}\`${entry.fileDark ? `, optional dark variant \`${entry.fileDark}\`` : ''}`,
      `- Size: ${entry.width}×${entry.height} pixels (${USE[entry.variant]})`,
      `- Alt text on the page: ${entry.alt}`,
      '',
      '```text',
      entry.prompt,
      '```'
    );
  }
  return `${lines.join('\n')}\n`;
}

function main(argv: readonly string[]): number {
  const doc = renderPromptsDoc(ILLUSTRATIONS);
  if (argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(PROMPTS_DOC, 'utf8');
    } catch {
      // A missing doc is drift too.
    }
    if (current !== doc) {
      console.error(
        'illustration-prompts.md is out of date: run pnpm exec tsx apps/website/scripts/illustration-prompts.ts'
      );
      return 1;
    }
    console.log(`illustration-prompts.md is current (${ILLUSTRATIONS.length} slots)`);
    return 0;
  }
  writeFileSync(PROMPTS_DOC, doc);
  console.log(`wrote illustration-prompts.md (${ILLUSTRATIONS.length} slots)`);
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  process.exitCode = main(process.argv.slice(2));
}
